#!/usr/bin/env bash
#
# Static quality metrics for flux-core — the objective proxies that back the
# "current coverage picture" in docs/quality.md.
#
# Everything here is computed with POSIX tools only (find/wc/grep/awk), so it
# runs on the distro toolchain with no extra installs and no compilation. The
# numbers are therefore *stable and reproducible*: they describe the source
# tree, not a build.
#
# Two families of numbers are reported:
#
#   * Size / shape      — .rs files and lines of code per workspace member.
#   * Test presence     — count of `#[test]` / `#[tokio::test]` attributes per
#                         member and the list of files that contain none.
#
# Caveats worth knowing before quoting these numbers:
#
#   * The test count is a *static attribute count*, not the number of tests the
#     harness will run. `cargo test --workspace -- --list` is authoritative for
#     the latter (see `--cargo-tests`), but it needs a full build.
#   * Lines include comments, doc comments, blanks and `#[cfg(test)]` bodies.
#     This is deliberately the "wc -l" definition: it is what a reviewer can
#     reproduce by hand.
#   * Integration tests live in `tests/` and are attributed to the root package,
#     because that is how Cargo builds them.
#
# Usage:
#   scripts/quality_metrics.sh                 # markdown tables on stdout
#   scripts/quality_metrics.sh --cargo-tests   # add harness-counted test totals
#   scripts/quality_metrics.sh --min-loc 100   # "no tests" cutoff (default 100)
#   scripts/quality_metrics.sh --strict        # exit 1 if any file >= cutoff has no test
#
# Exit codes: 0 ok, 1 --strict found an untested file, 2 bad usage / missing tool.

set -euo pipefail

cd "$(dirname "$0")/.."

MIN_LOC=100
WITH_CARGO_TESTS=0
STRICT=0

usage() {
    sed -n '2,40p' "$0" | sed 's/^# \{0,1\}//'
}

while [ $# -gt 0 ]; do
    case "$1" in
        --cargo-tests) WITH_CARGO_TESTS=1 ;;
        --strict)      STRICT=1 ;;
        --min-loc)
            shift
            MIN_LOC="${1:-}"
            case "$MIN_LOC" in
                ''|*[!0-9]*) echo "error: --min-loc needs a positive integer" >&2; exit 2 ;;
            esac
            ;;
        -h|--help) usage; exit 0 ;;
        *) echo "error: unknown argument: $1" >&2; usage >&2; exit 2 ;;
    esac
    shift
done

for tool in find wc grep awk; do
    command -v "$tool" >/dev/null 2>&1 || { echo "error: required tool '$tool' not found" >&2; exit 2; }
done

# --- helpers ---------------------------------------------------------------

rs_files() { find "$1" -type f -name '*.rs' 2>/dev/null | sort; }

count_lines() { # stdin: file list
    local files
    files=$(cat)
    [ -n "$files" ] || { echo 0; return; }
    # shellcheck disable=SC2086 # word splitting is intended: one path per file
    wc -l $files | awk 'END { print $1 }'
}

count_tests() { # stdin: file list
    local files
    files=$(cat)
    [ -n "$files" ] || { echo 0; return; }
    # `|| true`: grep exits 1 when a member has no test attribute at all, and
    # under `pipefail` that would abort the script instead of reporting zero.
    # shellcheck disable=SC2086
    { grep -hE '^[[:space:]]*#\[(tokio::)?test(\(|])' $files 2>/dev/null || true; } |
        wc -l | awk '{ print $1 }'
}

files_without_tests() { # stdin: file list
    local f
    while IFS= read -r f; do
        [ -n "$f" ] || continue
        grep -qE '^[[:space:]]*#\[(tokio::)?test(\(|])' "$f" 2>/dev/null || printf '%s\n' "$f"
    done
}

# --- member list -----------------------------------------------------------

# Every path here is a workspace member root as far as source layout goes.
members=""
for d in crates/*/; do
    [ -f "${d}Cargo.toml" ] || continue
    members="${members}${d%/}
"
done
members="${members}src
tests"
# `examples`/`benches` are not workspace members but are part of the code base a
# reviewer cares about; they are reported as separate rows with a "(non-member)"
# marker so nobody mistakes them for shipped code.
extras="examples
benches"

# --- snapshot header -------------------------------------------------------

printf '<!-- generated by scripts/quality_metrics.sh — do not edit by hand -->\n'
printf 'Snapshot: `%s`' "$(date -u '+%Y-%m-%dT%H:%M:%SZ')"
if git rev-parse --short HEAD >/dev/null 2>&1; then
    printf ' at commit `%s`' "$(git rev-parse --short HEAD)"
    if [ -n "$(git status --porcelain 2>/dev/null)" ]; then
        printf ' **plus uncommitted changes**'
    fi
fi
printf '\n\n'

# --- per-member table ------------------------------------------------------

echo '### Code size and test presence per workspace member'
echo
echo '| Member | `.rs` files | Lines | `#[test]` attributes | Files w/o tests |'
echo '|---|---:|---:|---:|---:|'

total_files=0
total_lines=0
total_tests=0
untested_all=""

row_for() { # $1 label, $2 path, $3 = 1 if the files count as shipped code
    local label="$1" path="$2" shipped="${3:-1}" files lines tests untested n_untested
    files=$(rs_files "$path")
    [ -n "$files" ] || return 0
    lines=$(printf '%s\n' "$files" | count_lines)
    tests=$(printf '%s\n' "$files" | count_tests)
    untested=$(printf '%s\n' "$files" | files_without_tests)
    n_untested=$(printf '%s' "$untested" | grep -c . || true)
    printf '| `%s` | %s | %s | %s | %s |\n' \
        "$label" \
        "$(printf '%s\n' "$files" | grep -c .)" \
        "$lines" "$tests" "$n_untested"
    total_files=$((total_files + $(printf '%s\n' "$files" | grep -c .)))
    total_lines=$((total_lines + lines))
    total_tests=$((total_tests + tests))
    # Examples and benches are harnesses, not shipped code: they are reported
    # for size but must not pollute the "no tests" list.
    if [ -n "$untested" ] && [ "$shipped" = "1" ]; then
        untested_all="${untested_all}${untested}
"
    fi
}

while IFS= read -r m; do
    [ -n "$m" ] || continue
    row_for "$m" "$m"
done <<EOF
$members
EOF

while IFS= read -r m; do
    [ -n "$m" ] || continue
    row_for "$m (non-member)" "$m" 0
done <<EOF
$extras
EOF

echo
printf '**Total:** %s files, %s lines, %s test attributes.\n\n' \
    "$total_files" "$total_lines" "$total_tests"

# --- untested files --------------------------------------------------------

echo "### Files with no \`#[test]\`/\`#[tokio::test]\` (>= ${MIN_LOC} lines)"
echo
echo 'Module roots (`lib.rs`) that only re-export and files below the cutoff are'
echo 'excluded; the full list is available with `--min-loc 0`.'
echo

# shellcheck disable=SC2086
if [ -n "$untested_all" ]; then
    printf '%s' "$untested_all" | grep . | while IFS= read -r f; do
        loc=$(wc -l <"$f" | awk '{ print $1 }')
        if [ "$loc" -ge "$MIN_LOC" ]; then
            printf '%s %s\n' "$loc" "$f"
        fi
    done | sort -rn | awk '{ printf "- %s — %s lines\n", $2, $1 }'
else
    echo '_none_'
fi
echo

# --- optional harness-counted tests ---------------------------------------

if [ "$WITH_CARGO_TESTS" -eq 1 ]; then
    echo '### Harness-counted tests (`cargo test --lib -- --list` per member)'
    echo
    echo 'Authoritative: this is what `cargo test` will actually run, so it can'
    echo 'differ from the attribute count above (`#[cfg]`-gated modules, macros).'
    echo 'Requires a full build, so this section is opt-in.'
    echo
    if ! command -v cargo >/dev/null 2>&1; then
        echo '_cargo not found — skipped_'
    elif ! cargo test --workspace --lib --tests -- --list >/dev/null 2>&1; then
        echo '_the test targets do not build right now (compile error?) — skipped_'
    else
        total=$(cargo test --workspace --lib --tests -- --list 2>/dev/null | grep -c ': test$' || true)
        printf '| Scope | Tests |\n|---|---:|\n'
        for pkg in flux-types flux-common flux-router flux-dns flux-transport \
                   flux-protocol flux-inbound flux-outbound flux-app; do
            n=$(cargo test -p "$pkg" --lib -- --list 2>/dev/null | grep -c ': test$' || true)
            printf '| `%s` (unit) | %s |\n' "$pkg" "$n"
        done
        n=$(cargo test -p flux-core --tests -- --list 2>/dev/null | grep -c ': test$' || true)
        printf '| `flux-core` (`tests/` integration) | %s |\n' "$n"
        printf '| **Total** | **%s** |\n' "$total"
        echo
        echo 'Note: `--lib --tests` excludes examples, benches and doc-tests, so this'
        echo 'is the count of tests `cargo test --workspace` runs, not of `#[test]`'
        echo 'attributes in the tree.'
    fi
    echo
fi

# --- strict gate -----------------------------------------------------------

if [ "$STRICT" -eq 1 ]; then
    offenders=0
    if [ -n "$untested_all" ]; then
        while IFS= read -r f; do
            [ -n "$f" ] || continue
            loc=$(wc -l <"$f" | awk '{ print $1 }')
            [ "$loc" -ge "$MIN_LOC" ] && offenders=$((offenders + 1))
        done <<EOF
$(printf '%s' "$untested_all" | grep . || true)
EOF
    fi
    if [ "$offenders" -gt 0 ]; then
        echo "strict: $offenders source file(s) with >= ${MIN_LOC} lines carry no test" >&2
        exit 1
    fi
fi